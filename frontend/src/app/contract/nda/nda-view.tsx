"use client";

import type { ReactNode } from "react";
import { Articles, DocShell, Loading, Parties, Signs, useQuote } from "../doc-kit";

// 비밀유지계약서(NDA). 견적 토큰이 있으면 고객사와 과업명을 채우고, 없으면 상담 단계에서 쓰는 빈 양식이다.
export default function NdaView() {
  const { token, quote, error, ready } = useQuote(false);
  if (!ready) return <Loading error={error} />;

  const subject = quote ? <>「{quote.title}」 도입·구축</> : <>AI 상담 접수 시스템 도입·구축</>;
  const articles: [string, ReactNode][] = [
    ["목적", <>이 계약은 갑과 을이 {subject}(이하 &ldquo;이 건&rdquo;)의 상담, 견적, 개발 수행을 위하여 서로에게 공개하는 비밀정보를 보호하는 것을 목적으로 한다.</>],
    ["비밀정보", <>비밀정보란 서면, 전자 파일, 구두 등 형태와 관계없이 한쪽이 이 건과 관련하여 상대방에게 제공한 업무 자료, 고객·거래 정보, 개인정보, 기술 정보, 시스템 접근 정보, 영업 정보를 말한다. 구두로 알린 정보는 알릴 때 비밀임을 밝힌 것에 한한다.</>],
    ["비밀정보에서 제외되는 정보", <>다음 정보는 비밀정보로 보지 않는다.
      <ul className="st-contract-items">
        <li>받기 전에 이미 공개되어 있었거나, 받은 쪽의 잘못 없이 공개된 정보</li>
        <li>받기 전에 받은 쪽이 이미 적법하게 가지고 있던 정보</li>
        <li>비밀유지 의무가 없는 제3자에게서 적법하게 받은 정보</li>
        <li>받은 쪽이 비밀정보를 쓰지 않고 독자적으로 만든 정보</li>
        <li>법령, 법원 또는 행정기관의 요구로 공개해야 하는 정보. 이 경우 가능한 한 미리 상대방에게 알린다.</li>
      </ul></>],
    ["비밀유지 의무", <>받은 쪽은 비밀정보를 이 건의 목적에만 쓰고, 상대방의 서면(메일 포함) 동의 없이 제3자에게 공개하지 않는다. 비밀정보는 업무에 꼭 필요한 사람만 볼 수 있게 하고, 자신의 비밀정보를 관리하는 것과 같은 수준 이상으로 관리한다.</>],
    ["개인정보", <>갑이 제공하는 자료에 개인정보가 들어 있으면 을은 이 건 처리에 필요한 범위에서만 처리하고, 개인정보 보호법에 따른 안전조치를 하며, 목적을 이루면 지체 없이 파기한다. 실제 개인정보 대신 가명 처리한 자료나 예시 자료로 충분한 경우 그 자료를 쓴다.</>],
    ["자료의 반환과 파기", <>이 건이 끝나거나 상대방이 요청하면 받은 쪽은 비밀정보와 그 사본을 돌려주거나 파기하고, 상대방이 요청하면 파기한 사실을 메일 등으로 알린다. 다만 법령에 따라 보관해야 하는 자료는 그 기간 동안 보관할 수 있다.</>],
    ["권리의 유보", <>비밀정보를 제공하는 것은 그 정보에 대한 소유권, 지식재산권 등 권리를 넘기거나 사용을 허락하는 것이 아니다.</>],
    ["유효기간", <>이 계약은 서명한 날부터 효력이 생기고, 이 건의 상담이나 계약이 끝난 날부터 3년 동안 유지된다.</>],
    ["손해배상", <>한쪽이 이 계약을 위반하여 상대방에게 손해를 입힌 경우 그 손해를 배상한다. 상대방은 위반 행위를 멈추도록 요구할 수 있다.</>],
    ["기타", <>이 계약에서 정하지 않은 사항은 갑과 을이 협의하여 정한다. 이 계약과 관련한 분쟁은 먼저 협의로 해결하고, 소송이 필요하면 민사소송법에 따른 관할 법원에서 다툰다.</>],
  ];

  return <DocShell title="비밀유지계약서" token={token}
    notice="비밀유지계약서(NDA) 양식입니다. 실제 자료를 주고받기 전에 서명해 두면 됩니다. 인쇄·PDF 저장이나 Word로 저장해 서명하세요.">
    <h1 className="st-contract-title">비밀유지계약서</h1>
    <Parties quote={quote} tail="이 건과 관련하여 서로 공개하는 정보의 비밀을 지키기 위하여 다음과 같이 계약을 맺는다." />
    <Articles items={articles} />
    <p className="st-contract-closing">이 계약을 증명하기 위하여 계약서 2부를 작성하여 갑과 을이 서명 또는 날인한 뒤 각 1부씩 보관한다.</p>
    <Signs quote={quote} />
  </DocShell>;
}
